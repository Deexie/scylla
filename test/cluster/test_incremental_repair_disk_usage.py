# Reproducer for CUSTOMER-475 hypothesis.
#
# Hypothesis under test:
#   With tablet incremental repair, SSTables are partitioned into a "repaired"
#   set (sstables_repaired_at > 0) and an "unrepaired" set (== 0). Compaction
#   never mixes the two sets. So if we:
#       1. write a full generation of data,
#       2. run incremental repair (that data is now in the repaired set),
#       3. overwrite the SAME keys with a second generation (lands in the
#          unrepaired set),
#   then the old generation in the repaired set cannot be shadowed/purged by
#   the new generation via compaction, because the two sets are never
#   cross-compacted. Result: on-disk size grows ~2x, and only drops back after
#   the NEXT incremental repair moves the new data into the repaired set so the
#   two can finally compact together.
#
# A large per-row blob payload is used so the physical duplication is huge and
# unambiguous on disk.
#

from test.pylib.manager_client import ManagerClient
from test.pylib.util import wait_for_cql_and_get_hosts
from test.cluster.util import create_new_test_keyspace

import asyncio
import glob
import logging
import os
import time
import pytest

logger = logging.getLogger(__name__)

# Payload sizing: make each generation large so duplication is obvious.
NR_KEYS = 4000
BLOB_BYTES = 32 * 1024          # 32 KiB per row
# ~ NR_KEYS * BLOB_BYTES * RF = 4000 * 32KiB * 3 ~= 384 MiB per generation.
RF = 3
TABLETS = 8


def data_dir_size_bytes(workdir, ks, table):
    """Sum of all *-Data.db SSTable sizes for ks.table under a node workdir."""
    pattern = os.path.join(workdir, "data", f"{ks}*", f"{table}-*", "*-Data.db")
    total = 0
    for f in glob.glob(pattern):
        try:
            total += os.path.getsize(f)
        except OSError:
            pass
    return total


async def cluster_data_size(manager, servers, ks, table):
    sizes = []
    for s in servers:
        workdir = await manager.server_get_workdir(s.server_id)
        sizes.append(data_dir_size_bytes(workdir, ks, table))
    total = sum(sizes)
    logger.info(f"per-node sizes={sizes} total={total} ({total / (1024*1024):.1f} MiB)")
    return total


async def write_generation(cql, ks, nr_keys, blob_hex):
    # Uncompressible payload is generated by the caller; same keys every time so
    # generation N logically overwrites generation N-1.
    await asyncio.gather(*[
        cql.run_async(
            f"INSERT INTO {ks}.test (pk, data) VALUES ({k}, 0x{blob_hex});")
        for k in range(nr_keys)
    ])


async def flush_and_compact(manager, servers, ks):
    for s in servers:
        await manager.api.keyspace_flush(s.ip_addr, ks, "test")
    for s in servers:
        await manager.api.keyspace_compaction(s.ip_addr, ks, "test")


def make_blob_hex(nbytes, seed):
    # Pseudo-random, poorly-compressible bytes so LZ4 can't collapse the payload.
    import random
    rnd = random.Random(seed)
    return rnd.randbytes(nbytes).hex()


@pytest.mark.asyncio
async def test_incremental_repair_doubles_disk_on_overwrite(manager: ManagerClient):
    token = 'all'

    # Build a 3-node, 3-rack cluster (RF=3, tablets) so incremental tablet
    # repair is meaningful.
    servers = await manager.servers_add(
        RF,
        config={'tablet_load_stats_refresh_interval_in_seconds': 1},
        property_file=[{"dc": "dc1", "rack": f"r{i}"} for i in range(RF)])
    cql = manager.get_cql()

    ks = await create_new_test_keyspace(
        cql,
        "WITH replication = {{'class': 'NetworkTopologyStrategy', "
        "'replication_factor': {}}} AND tablets = {{'initial': {}}};".format(RF, TABLETS))

    # Large-blob table; no compression collapse, tombstone_gc=repair (the
    # incremental-repair-relevant mode).
    await cql.run_async(
        f"CREATE TABLE {ks}.test (pk int PRIMARY KEY, data blob) "
        f"WITH tombstone_gc = {{'mode':'repair'}} "
        f"AND compression = {{}};")

    hosts = await wait_for_cql_and_get_hosts(cql, servers, time.time() + 60)

    # Two poorly-compressible payloads of equal size, one per generation.
    blob_gen1 = make_blob_hex(BLOB_BYTES, seed=1)
    blob_gen2 = make_blob_hex(BLOB_BYTES, seed=2)

    # --- Generation 1 ---
    await write_generation(cql, ks, NR_KEYS, blob_gen1)
    await flush_and_compact(manager, servers, ks)
    size_gen1 = await cluster_data_size(manager, servers, ks, "test")
    logger.info(f"size after gen1 (pre-repair) = {size_gen1}")
    assert size_gen1 > 0

    # --- Incremental repair: gen1 moves into the repaired set ---
    await manager.api.tablet_repair(servers[0].ip_addr, ks, "test", token)
    await flush_and_compact(manager, servers, ks)
    size_after_repair1 = await cluster_data_size(manager, servers, ks, "test")
    logger.info(f"size after gen1 repair = {size_after_repair1}")

    # --- Generation 2: overwrite the SAME keys with a different large blob ---
    # This lands in the UNREPAIRED set. It shadows gen1 logically, but gen1 is
    # in the repaired set, so compaction cannot purge it.
    await write_generation(cql, ks, NR_KEYS, blob_gen2)
    await flush_and_compact(manager, servers, ks)
    size_gen2 = await cluster_data_size(manager, servers, ks, "test")
    logger.info(f"size after gen2 overwrite (pre-repair) = {size_gen2}")

    # HYPOTHESIS: disk grew ~2x because gen1 (repaired) and gen2 (unrepaired)
    # cannot cross-compact, so both physical copies of every key coexist.
    ratio = size_gen2 / size_after_repair1
    logger.info(f"growth ratio after overwrite = {ratio:.2f}")
    assert ratio > 1.8, (
        f"expected ~2x growth from repaired/unrepaired split, got {ratio:.2f} "
        f"(gen1={size_after_repair1}, gen2={size_gen2})")

    # --- Second incremental repair: gen2 moves into the repaired set ---
    # Now both generations are in the repaired set and can compact together;
    # the shadowed gen1 copies get purged and disk drops back toward 1x.
    await manager.api.tablet_repair(servers[0].ip_addr, ks, "test", token)
    await flush_and_compact(manager, servers, ks)
    size_after_repair2 = await cluster_data_size(manager, servers, ks, "test")
    logger.info(f"size after gen2 repair = {size_after_repair2}")

    reclaim_ratio = size_after_repair2 / size_gen2
    logger.info(f"reclaim ratio after 2nd repair = {reclaim_ratio:.2f}")
    assert reclaim_ratio < 0.7, (
        f"expected disk to drop back toward 1x after 2nd repair reconciled the "
        f"sets, got {reclaim_ratio:.2f} "
        f"(pre={size_gen2}, post={size_after_repair2})")
